/**
 * Bundles every prisma/migrations/<name>/migration.sql into
 * src/generated/migrations.ts. The app itself applies migrations with
 * `prisma migrate deploy`; this bundle exists so the tests can build a real
 * Postgres (PGlite) database from the very same SQL (src/test/memory-db.ts).
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "prisma/migrations");
const migrations = readdirSync(dir)
  .filter((name) => existsSync(join(dir, name, "migration.sql")))
  .sort()
  .map((name) => ({ name, sql: readFileSync(join(dir, name, "migration.sql"), "utf8") }));
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/migrations.ts"),
  `// Generated by scripts/bundle-migrations.mjs from prisma/migrations. Do not edit.\n` +
    `export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`bundle-migrations: bundled ${migrations.length} migrations`);
